#!/usr/bin/env python3
"""TotK-Recomp AArch64 Static Lifter & Code Generator.

Decompresses NSO binaries, analyzes control flow graphs and basic blocks,
and generates chunked C files with SIMDe NEON lowering and fast radix dispatch.
Includes --lift-stats mode for verifying 100% ISA coverage.
"""

import argparse
from collections import Counter
import hashlib
from pathlib import Path
import struct
import sys

from nso import Nso, R_AARCH64_RELATIVE
from lifter import Lifter, Unsupported, Insn, hx
import simd_c

FN_HEADER = """// Auto-generated by TotK-Recomp Static Lifter
#include "runtime/cpu.h"
#include "runtime/simd.h"

"""

TOTK_V143_JUMP_TABLES = {
    0x393bb0: (0x393ba0, 0x2d8626c, 6),
    0x596d30: (0x596d20, 0x2d89154, 9),
    0x598ef4: (0x598ee4, 0x2d89038, 9),
    0x5f2a9c: (0x5f2a90, 0x2d892e0, 5),
    0x6397d8: (0x6397cc, 0x2d88e7c, 7)
}


def read_encoded(img, off, enc, pc_base):
    fmt, app = enc & 0x0F, enc & 0x70
    if fmt == 0x0B: v, sz = struct.unpack_from('<i', img, off)[0], 4
    elif fmt == 0x03: v, sz = struct.unpack_from('<I', img, off)[0], 4
    elif fmt in (0x0C, 0x04): v, sz = struct.unpack_from('<q' if fmt == 0x0C else '<Q', img, off)[0], 8
    else: raise ValueError(f'unsupported {enc:#x}')
    if app == 0x10: v += off
    elif app == 0x30: v += pc_base
    return v, sz


def eh_frame_functions(n):
    img, hdr = n.image, n.eh_start
    if not hdr or hdr >= len(img): return []
    ver, ptr_enc, cnt_enc, tbl_enc = img[hdr:hdr + 4]
    off = hdr + 4
    _, sz = read_encoded(img, off, ptr_enc, hdr); off += sz
    count, sz = read_encoded(img, off, cnt_enc, hdr); off += sz
    starts = []
    for _ in range(count):
        loc, sz = read_encoded(img, off, tbl_enc, hdr); off += sz
        _, sz = read_encoded(img, off, tbl_enc, hdr); off += sz
        starts.append(loc)
    return starts


def discover_functions(nso: Nso, base: int):
    text_off, text_len = nso.text
    text_lo = base + text_off
    text_hi = text_lo + text_len
    starts = set()

    for a in eh_frame_functions(nso):
        if (a & 3) == 0 and text_lo <= base + a < text_hi:
            starts.add(base + a)

    for name, info, shndx, value, size in nso.syms:
        if (value & 3) == 0 and shndx and (info & 0xF) == 2 and text_lo <= base + value < text_hi:
            starts.add(base + value)

    for off, typ, sym, add in nso.relocs:
        if (add & 3) == 0 and typ == R_AARCH64_RELATIVE and text_lo <= base + add < text_hi:
            starts.add(base + add)

    # Discover PLT stubs (16-byte ADRP x16; LDR x17; ADD x16; BR x17)
    words = struct.unpack(f'<{text_len // 4}I', bytes(nso.image[text_off:text_off + text_len]))
    for i in range(len(words) - 3):
        if (words[i] & 0x9F00001F) == 0x90000010 and words[i + 3] == 0xD61F0220:
            starts.add(text_lo + i * 4)

    starts.add(text_lo)
    sorted_starts = sorted(starts)

    # Pairs of (start, end)
    functions = []
    for i, start in enumerate(sorted_starts):
        end = sorted_starts[i + 1] if i + 1 < len(sorted_starts) else text_hi
        functions.append((start, end))

    return functions


def lift_stats(nso_path: Path):
    print("=====================================================")
    print("  TotK-Recomp AArch64 Lifter Instruction Coverage")
    print("=====================================================")
    print(f"Loading module: {nso_path}")

    nso = Nso(nso_path)
    text_off, text_len = nso.text
    text_bytes = nso.image[text_off:text_off + text_len]
    word_count = text_len // 4

    print(f"Decompressed .text range: 0x{text_off:08x} - 0x{text_off + text_len:08x} ({text_len:,} bytes)")
    print(f"Total 4-byte instruction words: {word_count:,}")

    lifter = Lifter(base=0x7100000000, simd='c')

    unhandled = Counter()
    categories = Counter()
    total_lifted = 0
    functions_found = set()

    for idx in range(word_count):
        pc = 0x7100000000 + text_off + idx * 4
        w = struct.unpack_from('<I', text_bytes, idx * 4)[0]

        if (w & 0xFFC003E0) == 0xA98003E0 or w == 0xD503237F:
            functions_found.add(pc)

        try:
            insn = lifter.lift(w, pc)
            categories[insn.kind] += 1
            total_lifted += 1
        except Unsupported as e:
            unhandled[str(e)] += 1
        except Exception as e:
            unhandled[type(e).__name__] += 1

    print(f"\n--- Coverage Results ---")
    print(f"Disassembled Instructions : {total_lifted:,} / {word_count:,}")
    print(f"Identified Function Starts: {len(functions_found):,}")
    print(f"Instruction Categories Breakdown:")
    for cat, cnt in categories.most_common():
        pct = (cnt / word_count) * 100.0
        print(f"  - {cat:<16}: {cnt:>10,} ({pct:6.2f}%)")

    if unhandled:
        print(f"\n[WARNING] Unhandled Instructions/Mnemonics ({len(unhandled)} types):")
        for op, cnt in unhandled.most_common():
            print(f"  ! {op:<30}: {cnt:>8,} occurrences")
    else:
        print(f"\n[PASSED] Unhandled Mnemonics: 0 (100.0% AArch64 coverage)")

    print("=====================================================")
    return len(unhandled) == 0


def emit_function(fn_start: int, fn_end: int, words: list, lifter: Lifter, base: int, text_lo: int, text_hi: int):
    lines = [f"void f_{fn_start:x}(Cpu *c) {{"]
    fn_word_count = (fn_end - fn_start) // 4

    # Check for computed br (jump tables)
    has_computed_br = False
    for i in range(fn_word_count):
        pc = fn_start + i * 4
        rel_idx = (pc - text_lo) // 4
        if 0 <= rel_idx < len(words):
            w = words[rel_idx]
            if (w & 0xFFFFFC1F) == 0xD61F0000: # br xN
                rn = (w >> 5) & 31
                for j in range(max(0, i - 16), i):
                    prev_w = words[(fn_start + j * 4 - text_lo) // 4]
                    if (prev_w & 31) == rn:
                        if (prev_w & 0x1F000000) == 0x0B000000 or (prev_w & 0x9F000000) == 0x10000000:
                            has_computed_br = True
                            break
                if has_computed_br:
                    break

    # First pass: collect internal branch targets
    labels = set()
    if has_computed_br:
        for i in range(fn_word_count):
            labels.add(fn_start + i * 4)
    else:
        for i in range(fn_word_count):
            pc = fn_start + i * 4
            rel_idx = (pc - text_lo) // 4
            if 0 <= rel_idx < len(words):
                w = words[rel_idx]
                try:
                    ins = lifter.lift(w, pc)
                    if ins.kind in ('b', 'bcond') and fn_start <= ins.target < fn_end:
                        labels.add(ins.target)
                except Exception:
                    pass

    # Second pass: emit statements
    for i in range(fn_word_count):
        pc = fn_start + i * 4
        if pc in labels:
            lines.append(f"L_{pc:x}:;")

        rel_idx = (pc - text_lo) // 4
        if rel_idx < 0 or rel_idx >= len(words):
            lines.append(f"    rt_udf(c, {hx(pc)});")
            continue

        w = words[rel_idx]

        # Patch: blr x18 system dispatch
        if w == 0xD63F0240:
            lines.append(f"    c->x[30] = {hx(pc + 4)}; dispatch_blr_x18(c);")
            continue

        # Patch: signed jump tables
        rel_to_base = pc - base
        if rel_to_base in TOTK_V143_JUMP_TABLES:
            anchor, _, _ = TOTK_V143_JUMP_TABLES[rel_to_base]
            lines.append(f"    {{ uint64_t t = resolve_v143_jump_table({hx(anchor)}, (int32_t)c->x[18]); c->pc = t; rt_dispatch(c); return; }}")
            continue

        try:
            ins = lifter.lift(w, pc)
            k = ins.kind
            if k == 'op':
                lines.append(f"    {ins.code}")
            elif k == 'b':
                if fn_start <= ins.target < fn_end:
                    lines.append(f"    goto L_{ins.target:x};")
                else:
                    lines.append(f"    c->pc = {hx(ins.target)}; rt_dispatch(c); return;")
            elif k == 'bcond':
                if fn_start <= ins.target < fn_end:
                    lines.append(f"    if ({ins.cond}) goto L_{ins.target:x};")
                else:
                    lines.append(f"    if ({ins.cond}) {{ c->pc = {hx(ins.target)}; rt_dispatch(c); return; }}")
            elif k == 'bl':
                lines.append(f"    c->x[30] = {hx(pc + 4)}; c->pc = {hx(ins.target)}; rt_dispatch(c);")
            elif k == 'blr':
                lines.append(f"    c->pc = {ins.target}; c->x[30] = {hx(pc + 4)}; rt_dispatch(c);")
            elif k == 'br':
                if has_computed_br:
                    lines.append(f"    c->pc = {ins.target}; goto L_dispatch_{fn_start:x};")
                else:
                    lines.append(f"    c->pc = {ins.target}; rt_dispatch(c); return;")
            elif k == 'ret':
                lines.append("    return;")
            elif k == 'trap':
                lines.append(f"    rt_udf(c, {hx(pc)});")
            else:
                lines.append(f"    // {k}")
        except Exception as e:
            lines.append(f"    rt_udf(c, {hx(pc)}); /* {e} */")

    if has_computed_br:
        lines.append(f"L_dispatch_{fn_start:x}:;")
        cases = ' '.join(f"case {hx(p)}: goto L_{p:x};" for p in range(fn_start, fn_end, 4))
        lines.append(f"    switch (c->pc) {{ {cases} default: break; }}")
        lines.append(f"    rt_dispatch(c); return;")

    lines.append("}\n")
    return '\n'.join(lines)


def lift_module(nso_path: Path, out_dir: Path, base: int = 0x7100000000, chunk_size: int = 250, max_fns: int = 0):
    print(f"[Lifter] Loading module: {nso_path.name} at base 0x{base:x}")
    nso = Nso(nso_path)
    text_off, text_len = nso.text
    text_lo = base + text_off
    text_hi = text_lo + text_len

    words = struct.unpack(f'<{text_len // 4}I', bytes(nso.image[text_off:text_off + text_len]))
    lifter = Lifter(base=base, simd='c')

    functions = discover_functions(nso, base)
    if max_fns > 0 and len(functions) > max_fns:
        fn_map = {f[0]: f for f in functions}
        selected_set = set(f[0] for f in functions[:max_fns])
        # Always include key exported symbols in this module (nnMain, nninitStartup, etc.)
        for sym_name, sym_info, sym_shndx, sym_val, sym_sz in nso.syms:
            if sym_shndx and (sym_info & 0xF) == 2:
                addr = base + sym_val
                if addr in fn_map:
                    selected_set.add(addr)

        # Always include all relocations (vtables, function pointers)
        for off, typ, sym, add in nso.relocs:
            addr = base + add
            if addr in fn_map:
                selected_set.add(addr)

        # Always include all PLT stubs
        for i in range(len(words) - 3):
            if (words[i] & 0x9F00001F) == 0x90000010 and words[i + 3] == 0xD61F0220:
                if (text_lo + i * 4) in fn_map:
                    selected_set.add(text_lo + i * 4)

        # Always include all static constructors from DT_INIT_ARRAY
        init_arr_off = nso.dyn.get(25, 0)
        init_arr_sz = nso.dyn.get(27, 0)
        if init_arr_off and init_arr_sz:
            for p in struct.unpack_from(f"<{init_arr_sz // 8}Q", nso.image, init_arr_off):
                addr = base + p
                if addr in fn_map:
                    selected_set.add(addr)

        # Always include all function pointers formed via ADRP + ADD
        for i in range(len(words) - 1):
            w1, w2 = words[i], words[i + 1]
            if (w1 & 0x9F000000) == 0x90000000 and (w2 & 0xFF800000) == 0x91000000:
                rd1 = w1 & 0x1F
                rn2 = (w2 >> 5) & 0x1F
                if rn2 == rd1:
                    immlo = (w1 >> 29) & 3
                    immhi = (w1 >> 5) & 0x7FFFF
                    imm21 = (immhi << 2) | immlo
                    if imm21 & 0x100000: imm21 -= 0x200000
                    pc_page = (text_lo + i * 4) & ~0xFFF
                    page = pc_page + (imm21 << 12)
                    imm12 = (w2 >> 10) & 0xFFF
                    if (w2 >> 22) & 1: imm12 <<= 12
                    target = page + imm12
                    if target in fn_map:
                        selected_set.add(target)

        # Transitive reachability closure: expand all branch and call targets
        visited = set()
        to_visit = list(selected_set)
        while to_visit:
            addr = to_visit.pop()
            if addr in visited:
                continue
            visited.add(addr)
            if addr in fn_map:
                f_start, f_end = fn_map[addr]
                for w_idx in range((f_start - text_lo) // 4, (f_end - text_lo) // 4):
                    if w_idx < len(words):
                        w = words[w_idx]
                        if (w >> 26) in (5, 37):
                            imm26 = w & 0x03FFFFFF
                            if imm26 & 0x02000000: imm26 -= 0x04000000
                            target = text_lo + w_idx * 4 + imm26 * 4
                            if target in fn_map and target not in visited:
                                to_visit.append(target)
                                selected_set.add(target)

        functions = [f for f in functions if f[0] in selected_set]

    print(f"  Discovered {len(functions):,} functions across {text_len:,} bytes text")
    out_dir.mkdir(parents=True, exist_ok=True)

    chunk_files = []
    chunk_count = (len(functions) + chunk_size - 1) // chunk_size

    for ci in range(chunk_count):
        chunk_fns = functions[ci * chunk_size:(ci + 1) * chunk_size]
        chunk_file = out_dir / f"{nso_path.stem}_chunk_{ci:04d}.c"

        body = [FN_HEADER]
        for fn_start, fn_end in chunk_fns:
            fn_code = emit_function(fn_start, fn_end, words, lifter, base, text_lo, text_hi)
            body.append(fn_code)

        chunk_file.write_text('\n'.join(body))
        chunk_files.append(chunk_file)

    print(f"[Lifter] Emitted {len(chunk_files)} chunks for {nso_path.stem}")
    return [fn_start for fn_start, _ in functions], chunk_files


def main():
    parser = argparse.ArgumentParser(description="TotK-Recomp AArch64 Static Lifter")
    parser.add_argument('nso', type=str, nargs='?', default=None, help="Path to input NSO binary")
    parser.add_argument('--base', type=lambda s: int(s, 0), default=0x7100000000, help="Base address")
    parser.add_argument('--lift-stats', type=str, default=None, help="Analyze NSO binary and print instruction coverage stats")
    parser.add_argument('--out-dir', type=str, default="work/gen", help="Output directory for C source files")
    parser.add_argument('--chunk-size', type=int, default=250, help="Functions per C file chunk")
    parser.add_argument('--max-fns', type=int, default=0, help="Limit number of functions to lift (0 = all)")
    args = parser.parse_args()

    if args.lift_stats:
        success = lift_stats(Path(args.lift_stats))
        sys.exit(0 if success else 1)

    if args.nso:
        lift_module(Path(args.nso), Path(args.out_dir), base=args.base, chunk_size=args.chunk_size, max_fns=args.max_fns)
    else:
        parser.print_help()


if __name__ == '__main__':
    main()
